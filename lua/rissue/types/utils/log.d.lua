--- Logging levels where:
--- - off: 5
--- - error: 4
--- - warn: 3
--- - info: 2
--- - debug: 1
--- - trace: 0
---@alias rissue.log.level
---| 0 trace
---| 1 debug
---| 2 info
---| 3 warn
---| 4 error
---| 5 off

--- Logging levels where:
--- - off: 5
--- - error: 4
--- - warn: 3
--- - info: 2
--- - debug: 1
--- - trace: 0
---@alias rissue.log.level.named
---| "trace" trace
---| "debug" debug
---| "info" info
---| "warn" warn
---| "error" error
---| "off" off

---@class __rissue.log._levels<T>
---@field trace T
---@field debug T
---@field info T
---@field warn T
---@field error T
---@field off T

---@class rissue.log.builtin
---@field color_enabled boolean

